// Turns the knowledge base's JSON tables into SQL for D1 (and for node:sqlite in tests).

const q = v => {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL'
  if (typeof v === 'boolean') return v ? '1' : '0'
  return `'${String(v).replace(/'/g, "''")}'`
}
const insert = (table, row) =>
  `INSERT INTO ${table} (${Object.keys(row).join(', ')}) VALUES (${Object.values(row).map(q).join(', ')});`

// Where a work's image is loaded from. Own works' documentation images go to R2 under kb/own/doc/;
// received works use the file of the same name on Wikipedia, which serves Commons and its own
// non-free files alike, until they are copied into R2.
export function imageUrl(work) {
  if (!work.image) return null
  // thumb.wikimedia.org is not a real host; the same path is served by upload.wikimedia.org.
  if (/^https:\/\//.test(work.image)) return work.image.replace('://thumb.wikimedia.org/', '://upload.wikimedia.org/')
  // A note in place of a file name (an image Jon supplied that isn't in the tables yet).
  if (!/\.(jpe?g|png|gif|webp|svg|tiff?)$/i.test(work.image)) return null
  if (work.origin === 'own') return `/img/kb/own/doc/${encodeURIComponent(work.image)}`
  return `https://en.wikipedia.org/wiki/Special:FilePath/${encodeURIComponent(work.image.replace(/ /g, '_'))}?width=800`
}

// Own works stay unpublished until Jon's editorial pass; a row may also say so itself.
export function visibilityOf(work) {
  if (work.visibility) return work.visibility
  if (work.private) return 'private'
  return work.origin === 'own' ? 'draft' : 'public'
}

export function buildSeed(tables) {
  const problems = []

  const workIds = new Set(tables.works.map(w => w.id))
  const idiomIds = new Set(tables.idioms.map(i => i.id))
  const archetypeIds = new Set(tables.archetypes.map(a => a.id))
  const lines = [
    '-- Generated by scripts/build-seed.mjs. Do not edit by hand.',
    'DELETE FROM links;', 'DELETE FROM readings;', 'DELETE FROM works;', 'DELETE FROM tropes;',
    'DELETE FROM idioms;', 'DELETE FROM techniques;', 'DELETE FROM archetypes;', 'DELETE FROM facets;',
  ]

  tables.works.forEach((w, sort) => lines.push(insert('works', {
    id: w.id, title: w.title, who: w.who, form: w.form,
    origin: w.origin, recognition: w.recognition, in_copyright: !!w.inCopyright,
    visibility: visibilityOf(w), image_url: imageUrl(w), sort, body: JSON.stringify(w),
  })))
  for (const r of tables.readings) {
    if (!workIds.has(r.work)) { problems.push(`reading for unknown work ${r.work}`); continue }
    lines.push(insert('readings', { work: r.work, viewer: r.viewer, archetype: r.archetype, body: JSON.stringify(r) }))
  }
  tables.tropes.forEach((t, sort) => lines.push(insert('tropes', {
    id: t.id, name: t.name, turn: t.turn, origin: t.origin, sort, body: JSON.stringify(t),
  })))
  tables.idioms.forEach((i, sort) => lines.push(insert('idioms', {
    id: i.id, phrase: i.phrase, kind: i.kind, skeuomorph: !!i.skeuomorph, sort, body: JSON.stringify(i),
  })))
  tables.techniques.forEach((t, sort) => lines.push(insert('techniques', {
    id: t.id, name: t.name, sort, body: JSON.stringify(t),
  })))
  tables.archetypes.forEach((a, sort) => lines.push(insert('archetypes', {
    id: a.id, name: a.name, sort, body: JSON.stringify(a),
  })))

  const link = (fromKind, fromId, toId, sort, kinds) => {
    const toKind = kinds.find(([, ids]) => ids.has(toId))?.[0]
    if (!toKind) { problems.push(`${fromKind} ${fromId} points at unknown ${toId}`); return }
    lines.push(insert('links', { from_kind: fromKind, from_id: fromId, to_kind: toKind, to_id: toId, sort }))
  }
  const anchorKinds = [['work', workIds], ['idiom', idiomIds]]
  const seen = new Set()
  const once = (k, f) => { if (!seen.has(k)) { seen.add(k); f() } }
  for (const t of tables.tropes) (t.anchors ?? []).forEach((a, i) => once(`trope/${t.id}/${a}`, () => link('trope', t.id, a, i, anchorKinds)))
  for (const t of tables.techniques) {
    (t.anchors ?? []).forEach((a, i) => once(`technique/${t.id}/${a}`, () => link('technique', t.id, a, i, anchorKinds)))
    ;(t.archetypes ?? []).forEach((a, i) => once(`technique/${t.id}/a/${a}`, () => link('technique', t.id, a, i, [['archetype', archetypeIds]])))
  }
  for (const a of tables.archetypes) (a.anchors ?? []).forEach((w, i) => once(`archetype/${a.id}/${w}`, () => link('archetype', a.id, w, i, anchorKinds)))

  for (const f of facetRows(tables)) lines.push(insert('facets', f))
  return { sql: lines.join('\n') + '\n', problems }
}

const words = s => s.replace(/([a-z])([A-Z])/g, '$1 $2').toLowerCase()
const ordinal = n => n + (n % 100 >= 11 && n % 100 <= 13 ? 'th' : ['th', 'st', 'nd', 'rd'][n % 10] ?? 'th')

/** The artist named before the first comma or middle dot of a work's "who" line. */
export const artistOf = who => (who ? who.split(' · ')[0].split(', ')[0].trim() || null : null)

/** The century of the first year (or "10th century") in a work's dates. */
export function centuryOf(work) {
  const text = [work.when, work.who].filter(Boolean).join(' ')
  const named = text.match(/\b(\d{1,2})(?:st|nd|rd|th) century\b/)
  if (named) return Number(named[1])
  const year = text.match(/\b(\d{3,4})\b/)
  return year ? Math.floor((Number(year[1]) - 1) / 100) + 1 : null
}

/** The rewrites a reading's chain uses, by the names written in it (setDegree, repeat, trace...). */
export const rewritesOf = chain => (chain && /^[A-Za-z_]\w*[.(]/.test(chain) ? [...new Set([...chain.matchAll(/\.([A-Za-z_]\w*)\(/g)].map(m => m[1]))] : [])

/** Every (work, facet, value, label) row for the works page's faceted search. */
export function facetRows(tables) {
  const rows = new Map()
  const add = (work, facet, value, label = value) => {
    if (value === null || value === undefined || value === '') return
    rows.set(`${work}\u0000${facet}\u0000${value}`, { work, facet, value: String(value), label: String(label) })
  }
  const names = (list, key = 'name') => new Map((list ?? []).map(x => [x.id, x[key]]))
  const tropes = names(tables.tropes), techniques = names(tables.techniques), archetypes = names(tables.archetypes)
  const colors = (tables.colors ?? []).map(c => c.material).filter(Boolean)
    .map(m => [m, new RegExp(`(^|[^A-Za-z])${m.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}($|[^A-Za-z])`)])

  for (const w of tables.works) {
    add(w.id, 'artist', artistOf(w.who))
    add(w.id, 'origin', w.origin, w.origin === 'own' ? 'own' : 'received')
    add(w.id, 'form', w.form)
    const c = centuryOf(w)
    if (c) add(w.id, 'century', String(c).padStart(2, '0'), `${ordinal(c)} century`)
    for (const [m, re] of colors) if (w.materials && re.test(w.materials)) add(w.id, 'color', m)
  }
  for (const r of tables.readings) {
    if (r.archetype) add(r.work, 'archetype', r.archetype, archetypes.get(r.archetype) ?? r.archetype)
    for (const d of r.frameRead?.domains ?? []) add(r.work, 'domain', d, words(d))
    if (r.frameRead?.stance) add(r.work, 'stance', r.frameRead.stance)
    for (const m of rewritesOf(r.chain)) add(r.work, 'rewrite', m)
  }
  for (const t of tables.tropes) for (const a of t.anchors ?? []) add(a, 'trope', t.id, t.name)
  for (const t of tables.techniques) for (const a of t.anchors ?? []) add(a, 'technique', t.id, t.name)
  for (const a of tables.archetypes) for (const wk of a.anchors ?? []) add(wk, 'archetype', a.id, a.name)
  const workIds = new Set(tables.works.map(w => w.id))
  return [...rows.values()].filter(r => workIds.has(r.work))
}

export const CROCKFORD = '0123456789ABCDEFGHJKMNPQRSTVWXYZ'

/** A proof-mark code as typed or scanned, in Crockford's canonical form, or null if it can't be one. */
export function normalizeCode(raw) {
  const s = String(raw).toUpperCase().replace(/-/g, '').replace(/[IL]/g, '1').replace(/O/g, '0')
  return s.length === 5 && [...s].every(ch => CROCKFORD.includes(ch)) ? s : null
}

// Issued proof-mark codes (codes.csv from palette/proof_stamp/qr) as SQL that adds new codes and
// never touches a registered one, so it is safe to run again after printing more sheets.
export function buildProofCodes(csv) {
  const problems = []
  const lines = ['-- Generated by scripts/build-seed.mjs. Adds issued codes; never changes a registered one.']
  for (const row of csv.trim().split(/\r?\n/).slice(1)) {
    const raw = row.split(',')[0]
    const code = normalizeCode(raw)
    if (!code || code !== raw.trim()) { problems.push(`not a canonical code: ${raw}`); continue }
    lines.push(`INSERT OR IGNORE INTO proofs (code) VALUES ('${code}');`)
  }
  return { sql: lines.join('\n') + '\n', problems }
}
